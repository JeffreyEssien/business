// Writes the portfolio template library (src/modules/portfolio/template-library.ts)
// into a migration so the database seeds new portfolios from exactly the same data the
// public gallery previews. Run: node scripts/generate-portfolio-templates.mjs
// tests/unit/portfolio-templates.test.mjs fails if the migration and library differ.
import { writeFile } from 'node:fs/promises';
import { portfolioTemplateLibrary } from '../src/modules/portfolio/template-library.ts';

export const TEMPLATE_MIGRATION =
  'supabase/migrations/202611120005_portfolio_template_library_photos.sql';
const MARKER = '$templates$';

/** The database row shape for each template, in library order. */
export function templateRows() {
  return portfolioTemplateLibrary.map((template) => ({
    key: template.key,
    name: template.name,
    description: template.description,
    audience: template.audience,
    defaultPreset: template.defaultPreset,
    sortOrder: template.sortOrder,
    tokens: template.tokens,
    sections: template.sections,
    items: template.items,
  }));
}

export function renderMigration() {
  const json = JSON.stringify(templateRows(), null, 1);
  if (json.includes(MARKER)) throw new Error('Template text cannot contain the SQL marker.');
  return `-- Portfolio template library (docs/plans/portfolio-templates.md §4): 24 templates.
-- GENERATED by scripts/generate-portfolio-templates.mjs from
-- src/modules/portfolio/template-library.ts. Do not edit by hand; change the library
-- and add a new generated migration instead.
--
-- Existing templates are updated in place. Only new portfolios are seeded from these
-- rows, so portfolios that already exist keep their own content and look.

insert into public.site_templates (
  key, site_kind, name, description, audience, default_preset, default_tokens,
  default_sections, default_items, sort_order)
select t ->> 'key', 'PORTFOLIO', t ->> 'name', t ->> 'description', t ->> 'audience',
  t ->> 'defaultPreset', t -> 'tokens', t -> 'sections', t -> 'items', (t ->> 'sortOrder')::integer
from jsonb_array_elements(${MARKER}${json}${MARKER}::jsonb) t
on conflict (key) do update set
  name = excluded.name,
  description = excluded.description,
  audience = excluded.audience,
  default_preset = excluded.default_preset,
  default_tokens = excluded.default_tokens,
  default_sections = excluded.default_sections,
  default_items = excluded.default_items,
  sort_order = excluded.sort_order;
`;
}

export function migrationJson(sql) {
  const start = sql.indexOf(MARKER);
  const end = sql.indexOf(MARKER, start + MARKER.length);
  if (start < 0 || end < 0) throw new Error('Template JSON not found in the migration.');
  return JSON.parse(sql.slice(start + MARKER.length, end));
}

if (import.meta.url === `file://${process.argv[1]}`) {
  await writeFile(TEMPLATE_MIGRATION, renderMigration());
  console.log(`Wrote ${TEMPLATE_MIGRATION} (${portfolioTemplateLibrary.length} templates).`);
}
